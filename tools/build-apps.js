#!/usr/bin/env node
/* Converts the bundled apps in tools/app-sources/ into CSP-friendly documents in apps/:
     • the single inline <script> becomes apps/js/<app>.js
     • every inline on*="…" handler becomes data-on-*="…" and is run by js/app-bridge.js
       – handlers written in the HTML are compiled into real functions (apps/js/<app>.handlers.js)
       – handlers built inside the app's scripts are run by the bridge's small, allow-listed interpreter
     • a strict per-app Content-Security-Policy <meta> is added (no 'unsafe-inline' for scripts)
   Run:  node tools/build-apps.js     (output is committed; re-run after editing a source) */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const GAS = 'https://script.google.com https://*.googleusercontent.com';
const APPS = {
  cryptocompass: { connect: 'https://api.coingecko.com ' + GAS, frame: 'https://cryptobubbles.net' },
  systemvault: { connect: GAS },
  trustvault: { connect: GAS },
  /* QR Seal already ships its own hash-pinned policy (one inline script, no inline handlers) and a self-test that
     checks it; it is kept as written and only the storage shim is added, pinned by its own hash. */
  qrseal: { keep: true },
};
const EVENTS = 'click|change|input|keydown|keyup|keypress|submit|dblclick|focus|blur|mouseover|mouseout|mousedown|mouseup|touchstart|paste|drop|dragover|dragleave|dragenter|contextmenu';
const RESERVED = new Set('this event true false null undefined return if else window document typeof void'.split(' '));
/** a handler fragment as it appears inside a JS string literal → what it looks like at run time, with each
    concatenated expression ('+ expr +') replaced by a placeholder literal */
const hole = (raw) => raw.replace(/\\''\s*\+[\s\S]*?\+\s*'\\'/g, "'X'").replace(/'\s*\+\s*[^']*?\s*\+\s*'/g, '0').replace(/\\'/g, "'");
const decodeEntities = (s) => s.replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

const crypto = require('crypto');
for (const [name, cfg] of Object.entries(APPS)) {
  let html = fs.readFileSync(path.join(root, 'tools/app-sources', name + '.html'), 'utf8');
  if (cfg.keep) {
    const shim = fs.readFileSync(path.join(root, 'js/app-shim.js'), 'utf8').replace(/\r/g, '');
    const hash = crypto.createHash('sha256').update(shim).digest('base64');
    html = html.replace(/(<meta http-equiv="Content-Security-Policy" content="[^"]*script-src 'sha256-[^']+')/, "$1 'sha256-" + hash + "'");
    html = html.replace(/<head>/i, '<head>\n<script data-app="' + name + '">' + shim + '</script>');
    fs.writeFileSync(path.join(root, 'apps', name + '.html'), html);
    for (const f of ['.js', '.handlers.js']) { try { fs.unlinkSync(path.join(root, 'apps/js', name + f)); } catch (e) { /* none */ } }
    console.log(name + ': kept as written (hash-pinned CSP); storage shim added and pinned by hash');
    continue;
  }
  html = html.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\n?/i, '');
  const m = html.match(/<script>([\s\S]*?)<\/script>/);
  if (!m || html.indexOf('<script>', m.index + 1) !== -1) throw new Error(name + ': expected exactly one inline script');
  let script = m[1];
  const before = html.slice(0, m.index), after = html.slice(m.index + m[0].length);

  /* 1. static handlers in the markup → compiled functions */
  const handlers = [];
  const staticRe = new RegExp('(\\s)on(' + EVENTS + ')=("([^"]*)"|\'([^\']*)\')', 'g');
  const markup = (part) => part.replace(staticRe, (all, sp, ev, q, d, s1) => {
    const code = decodeEntities(d != null ? d : s1);
    handlers.push(code);
    return sp + 'data-on-' + ev + '="#' + (handlers.length - 1) + '"';
  });
  const newBefore = markup(before), newAfter = markup(after);

  /* 2. handlers built inside the script (string templates) → data-on-* text, interpreted at run time */
  const dyn = [];
  const dynRe = new RegExp('(\\s)on(' + EVENTS + ')=(?=\\\\?["\'])', 'g');
  script = script.replace(dynRe, (all, sp, ev) => sp + 'data-on-' + ev + '=');
  // collect handler texts for validation: grab from the renamed pieces up to the closing quote
  const grab = /data-on-(?:[a-z]+)=(\\?)(["'])((?:\\.|(?!\2)[^\\])*)\2/g;
  let g;
  while ((g = grab.exec(script))) dyn.push(g[3]);

  /* 3. names the dynamic handlers reference (the interpreter may only reach these) */
  const names = new Set();
  for (const raw of dyn) {
    // replace string-concatenation holes ('+expr+') by a literal so the remainder is plain handler code
    const text = hole(raw);
    const stripped = text.replace(/'[^']*'|"[^"]*"/g, '""');
    for (const t of stripped.matchAll(/(^|[^.\w$])([A-Za-z_$][\w$]*)/g)) if (!RESERVED.has(t[2])) names.add(t[2]);
  }
  const scopeNames = [...names].sort();

  const hjs = '/* generated by tools/build-apps.js — do not edit */\n(function () {\n  var H = [\n' +
    handlers.map((c) => '    function (event) { ' + c + '\n    }').join(',\n') + '\n  ];\n' +
    '  var scope = {\n' + scopeNames.map((n) => '    ' + JSON.stringify(n) + ': function () { return typeof ' + n + " === 'undefined' ? undefined : " + n + '; }').join(',\n') + '\n  };\n' +
    '  ulyOSBridge.install(H, scope);\n})();\n';
  fs.writeFileSync(path.join(root, 'apps/js', name + '.js'), script.replace(/^\n+/, ''));
  fs.writeFileSync(path.join(root, 'apps/js', name + '.handlers.js'), hjs);

  const csp = "default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; media-src 'self' data: blob:; font-src 'self' data:; " +
    "connect-src 'self' " + cfg.connect + "; worker-src 'self' blob:; frame-src " + (cfg.frame || "'none'") + "; object-src 'none'; base-uri 'none'; form-action 'none'";
  let out = newBefore;
  out = out.replace(/<head>/i, '<head>\n<meta http-equiv="Content-Security-Policy" content="' + csp + '">\n<script src="../js/app-shim.js" data-app="' + name + '"></script>');
  out += '<script src="../js/app-bridge.js"></script>\n<script src="js/' + name + '.js"></script>\n<script src="js/' + name + '.handlers.js"></script>' + newAfter;
  fs.writeFileSync(path.join(root, 'apps', name + '.html'), out);
  console.log(name + ': ' + handlers.length + ' static handlers compiled, ' + dyn.length + ' dynamic handlers, scope names: ' + scopeNames.join(', '));
}

module.exports = { hole };
